function javaScript(num){
    var num = -2;
    if(num >= 0){
        console.log("Positive number", num);
    }
    else if(num <= 0){
        console.log("Negative number", num);
    }
    else
    {
        console.log("Equal number", num);
    }
}
javaScript();

